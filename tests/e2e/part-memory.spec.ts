import { expect, test } from "@playwright/test";

test("saved customer revision becomes a new quote with a privately explained price and a frozen customer quantity choice", async ({ page, browser }) => {
  const run = Date.now().toString(36);
  await page.goto("/kayit");
  await page.getByLabel("Ad soyad").fill("Parça Testi");
  await page.getByLabel("Firma adı").fill(`Hafıza Lazer ${run}`);
  await page.getByLabel("İş e-postası").fill(`hafiza-${run}@ornek.test`);
  await page.getByLabel("Şifre").fill(`Parca-${run}-Test!`);
  await page.getByRole("checkbox").check();
  await page.getByRole("button", { name: "Hesabı oluştur" }).click();
  await expect(page).toHaveURL(/\/panel\/kurulum/);
  await page.getByLabel("Dakika ücreti (₺/dk)").fill("60");
  await page.getByLabel("DKP / siyah sac (S235) kilogram fiyatı").fill("40");
  await page.getByRole("button", { name: "Kurulumu tamamla" }).click();
  await expect(page).toHaveURL(/\/panel(\?|$)/);
  await page.goto("/panel/musteriler");
  await page.getByLabel("Firma veya kişi adı").fill("Hafıza Müşterisi");
  await page.getByRole("button", { name: "Müşteri ekle" }).click();
  await expect(page.getByRole("status")).toBeVisible();
  await page.goto("/panel/teklifler");
  await page.getByRole("button", { name: "Yeni teklif" }).click();
  await expect(page).toHaveURL(/\/panel\/teklifler\//);
  const sample = await page.request.get("/ornek.dxf");
  await page.locator('input[type="file"]').setInputFiles({ name: "braket.dxf", mimeType: "application/dxf", buffer: await sample.body() });
  const item = page.locator("form").filter({ has: page.getByLabel("Kalem adı") });
  await expect(page.getByLabel("Kalem adı")).toHaveValue(/braket/);
  await item.getByLabel("Parça kodu").fill("BR-001");
  await item.getByLabel("Revizyon").fill("A");
  await item.getByLabel("Kalınlık (mm)").fill("3");
  await item.getByLabel("Adet", { exact: true }).fill("10");
  await item.getByRole("button", { name: "Kaydet", exact: true }).click();
  const customer = page.locator('select[name="customerId"]');
  await customer.selectOption({ label: "Hafıza Müşterisi" });
  await customer.locator("..").locator("..").getByRole("button", { name: "Kaydet", exact: true }).click();
  await page.getByRole("button", { name: "Revizyonu hafızaya kaydet" }).click();
  await expect(page.getByText(/Revizyon parça hafızasında/)).toBeVisible();
  await page.goto("/panel/parcalar");
  await expect(page.getByRole("heading", { name: /BR-001/ })).toBeVisible();
  await page.getByRole("button", { name: "Güncel fiyatla yeni teklif" }).click();
  await expect(page.getByLabel("Parça kodu")).toHaveValue("BR-001");
  await page.getByText("Fiyat neden değişti?", { exact: false }).click();
  await expect(page.getByRole("table", { name: "Birim fiyat bileşenlerinin karşılaştırması" })).toBeVisible();
  await page.getByText("Adet seçeneklerini düzenle", { exact: true }).click();
  await page.getByLabel("1. alternatif adı").fill("100 adet seri");
  await page.getByLabel("braket — 1. alternatif adedi").fill("100");
  await page.getByRole("button", { name: "Seçenekleri hesapla" }).click();
  await expect(page.getByRole("heading", { name: "100 adet seri" })).toBeVisible();
  await page.getByRole("button", { name: "Teklifi gönder" }).click();
  const publicUrl = await page.getByRole("link", { name: "Müşteri görünümü" }).getAttribute("href");
  const guest = await browser.newContext({ locale: "tr-TR" });
  const publicPage = await guest.newPage();
  await publicPage.goto(publicUrl!);
  await expect(publicPage.getByText("Fiyat neden değişti?", { exact: false })).toHaveCount(0);
  await expect(publicPage.getByText("Kâr", { exact: true })).toHaveCount(0);
  publicPage.once("dialog", (dialog) => dialog.accept());
  await publicPage.getByRole("button", { name: "100 adet seri seçeneğini onayla" }).click();
  await expect(publicPage.getByText(/tarihinde onaylandı/)).toBeVisible();
  await expect(publicPage.getByRole("cell", { name: "100", exact: true })).toBeVisible();
  await guest.close();
  await page.reload();
  await expect(page.getByText("Seçilen alternatif: 100 adet seri")).toBeVisible();
  await page.setViewportSize({ width: 375, height: 900 });
  await page.emulateMedia({ colorScheme: "dark" });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: test.info().outputPath("memory-accepted-mobile.png"), fullPage: true, caret: "initial" });
});
